  content: `# Europe by Night — Powers of the continent

## The Concord across borders
The Concord is a promise between cities, and a promise needs someone to
hold it. In practice it is held by the **Seconds**: a trusted figure in each
city, usually a Vampire or Werewolf, who stands for the city when a dispute
crosses a border. A Second has no army. They have a name, a record and a
reputation, and they are asked to hold a meeting, not to win one.

**How a dispute is heard.** A city that is wronged sends its Second to ask
the neutral city of the season for a **Long Table**. It sits at the full
moon, at a place no party owns: a hotel dining room, a closed cloister, a
night train's restaurant car. Each side's Second speaks once for the
city. Witnesses are heard, and the Table may call for a Ghost, a Ledger or
a road-keeper's testimony. No oath is taken. Lying to the Table is simply
remembered.

**What a judgement looks like.** A price, not a punishment: reparation in
goods or favours, a hostage held for a year, a road ceded, a name struck
from a roll. A judgement is written, signed by the Seconds present, and
carried by courier to every city. A party that ignores it is **named**: no
Second will sit with them, no road-keeper will take their toll, and the
Dead Letter Post will deliver nothing to their door until the debt is paid.

**Three precedents everyone cites.**
- **The Treaty of the Two Bridges.** Two cities, one river, a century of
  raids. The Table awarded each bank to the city across from it, so that
  neither could feed at home without the other's leave.
- **The Hostage of the Night Coach.** A court that broke the Concord was
  made to give up its heir, who has ridden the coach for sixty years and has
  never been seen to leave it.
- **The Struck Name.** A Second who sold a city's secret was struck from every
  roll, and every door in Europe closed. He still lives, and is still
  the standard warning.

## The Vigil across borders
The Vigil has no head. It has **lodges**, each a handful of cells that share
a safehouse and a phone tree. A lodge covers a region, not a country, and is
run by whoever has survived longest. Lodges swap news through
**correspondents**, who travel on foot or by rail and carry no weapons.

**Asking another country for help.** A cell sends a correspondent with a
written account: what it knows, what it needs, what it can offer. The other
lodge answers within a week or not at all. Help is lent, never given: a
safehouse, a name, a driver, a body. The borrower owes a matching service.

**When a cell breaks its own rules.** The Vigil's one shared rule: no cell
names another to an enemy. A cell that does is **cut out**: its safehouses
change, its numbers go dead, its name is passed to every lodge, and no one
will pick up. Often it is left to be found. A lodge that sends a hunter
against a Kind without cause is warned once. After that it is cut.

## Four powers that cross borders
**The Dead Letter Post.** Ghost couriers who carry anything to anyone
without opening it. *Wants:* the dead remembered; every parcel carries a
little of the sender's voice, and the Post keeps a copy. *Offers:* delivery
across any border, any road, any wall. *Meet it:* a postbox that is never
emptied, a letter addressed to someone not yet born, a quiet woman in a
post-office queue. *Cost to cross:* nothing is delivered to you again, and
nothing you sent is guaranteed to arrive.

**The Tallow Bank.** A Witch credit house with a branch in every city and a
ledger in none. *Wants:* to be owed. *Offers:* loans in years, favours or
hours of luck, with collateral held in candle-wax on a vault shelf. *Meet
it:* a quiet shop with a bell on the door and customers who look relieved.
*Cost to cross:* the collateral is called in, and what was lent is taken
back with interest.

**The Lean Table.** A Wendigo cartel that moves hunger across borders. It
finds the starving and feeds them, and feeds on what follows. *Wants:*
cities hungry and grateful. *Offers:* food, work, a bed, no questions.
*Meet it:* a charity canteen, a cheap shelter, a rise in people who never
leave. *Cost to cross:* it does not fight. It waits, and your own people
begin to arrive at its door.

**The Eaves Compact.** Gargoyles of many cities who keep a shared watch
from the rooftops and trade what they see. *Wants:* the old buildings
kept standing. *Offers:* warnings, never secrets, and no violence for hire.
*Meet it:* a surveyor, a conservator, an anonymous grant, the sense of
being watched from above. *Cost to cross:* your haven's roof is no longer
watched, and your enemies' warnings come with a smile.

## How the powers collide
- The Dead Letter Post will not carry a Long Table's summons to a named
  party, and the Tallow Bank will happily lend the named party the courier.
- The Lean Table feeds Vigil cells that have been cut out, and the cut-out
  cell is grateful. The Eaves Compact watches the Lean Table's canteens and
  warns anyone who asks, which the Lean Table counts as a secret sold.
- A Second who owes the Tallow Bank cannot be neutral, and every Second
  owes someone. The Concord holds because nobody wants to say so aloud.
- Use these as pressure: any dispute can be made worse by one of the four,
  and any of the four can be bought by a patient enough character.

Use when the story needs the continent behind it: a dispute between
cities, a breach of the Concord, a Vigil lodge, or a power with branches
everywhere.`,
