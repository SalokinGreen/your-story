const EVENT_FOCUS = [
  { range: [1, 7], focus: "Remote event" },
  { range: [8, 28], focus: "NPC action" },
  { range: [29, 35], focus: "Introduce a new NPC" },
  { range: [36, 45], focus: "Move toward a thread" },
  { range: [46, 52], focus: "Move away from a thread" },
  { range: [53, 55], focus: "Close a thread" },
  { range: [56, 67], focus: "PC negative" },
  { range: [68, 75], focus: "PC positive" },
  { range: [76, 83], focus: "Ambiguous event" },
  { range: [84, 92], focus: "NPC negative" },
  { range: [93, 100], focus: "NPC positive" },
];

/**
 * Generate a random event focus
 */
export function generateEventFocus(): { focus: string; roll: number } {
  const roll = rollD100();

  for (const entry of EVENT_FOCUS) {
    if (roll >= entry.range[0] && roll <= entry.range[1]) {
      return { focus: entry.focus, roll };
    }
  }

  return { focus: "Unknown", roll };
}

