/**
 * List of all available agmt table names for validation
 */
export const MYTHIC_TABLE_NAMES = Object.keys(
  ELEMENT_TABLES
) as ElementCategory[];

/**
 * Generate a random element from a specific category
 * @param category - The element category to roll on
 * @returns Random element from that category with roll number
 */
export function generateElement(category: ElementCategory): {
  element: string;
  roll: number;
  category: ElementCategory;
} {
  const table = ELEMENT_TABLES[category];
  if (!table) {
    console.error(`Unknown element category: ${category}`);
    return {
      element: `Unknown category: ${category}`,
      roll: 0,
      category,
    };
  }
  const roll = rollD100();
  const index = Math.min(roll - 1, table.length - 1);

  return {
    element: table[index],
    roll,
    category,
  };
}

/**
 * Generate a complex meaning (Action + Descriptor)
 * Uses the advanced meaning tables for richer results
 * @returns Action and descriptor pair
 */
export function generateComplexMeaning(): {
  action: string;
  descriptor: string;
  actionRoll: number;
  descriptorRoll: number;
} {
  const actionRoll = rollD100();
  const descriptorRoll = rollD100();

  const actionIndex = Math.min(
    actionRoll - 1,
    MEANING_TABLE_ACTION_1.length - 1
  );
  const descriptorIndex = Math.min(
    descriptorRoll - 1,
    MEANING_TABLE_DESCRIPTOR_1.length - 1
  );

  return {
    action: MEANING_TABLE_ACTION_1[actionIndex],
    descriptor: MEANING_TABLE_DESCRIPTOR_1[descriptorIndex],
    actionRoll,
    descriptorRoll,
  };
}

/**
 * Generate a detail (Descriptor + Subject)
 * @returns Descriptor and subject pair for adding detail
 */
export function generateDetail(): {
  descriptor: string;
  subject: string;
  descriptorRoll: number;
  subjectRoll: number;
} {
  const descriptorRoll = rollD100();
  const subjectRoll = rollD100();

  const descriptorIndex = Math.min(
    descriptorRoll - 1,
    MEANING_TABLE_DESCRIPTOR_2.length - 1
  );
  const subjectIndex = Math.min(
    subjectRoll - 1,
    MEANING_TABLE_ACTION_2.length - 1
  );

  return {
    descriptor: MEANING_TABLE_DESCRIPTOR_2[descriptorIndex],
    subject: MEANING_TABLE_ACTION_2[subjectIndex],
    descriptorRoll,
    subjectRoll,
  };
}

/**
 * Generate multiple elements from different categories for rich descriptions
 * @param categories - Array of categories to roll on
 * @returns Array of generated elements
 */
export function generateMultipleElements(categories: ElementCategory[]): Array<{
  element: string;
  roll: number;
  category: ElementCategory;
}> {
  return categories.map((category) => generateElement(category));
}

/**
 * Generate a random name using the name syllables
 * @param syllables - Number of syllables (1-4, default: 2)
 * @returns Generated name
 */
export function generateName(syllables: number = 2): {
  name: string;
  rolls: number[];
} {
  syllables = Math.max(1, Math.min(4, syllables));
  const rolls: number[] = [];
  const parts: string[] = [];

  for (let i = 0; i < syllables; i++) {
    const roll = rollD100();
    rolls.push(roll);
    const index = Math.min(roll - 1, ELEMENTS_NAMES.length - 1);
    parts.push(ELEMENTS_NAMES[index]);
  }

  return {
    name: parts.join(""),
    rolls,
  };
}
