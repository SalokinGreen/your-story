// "Normal Yes"/"Normal No" rather than a bare "Yes"/"No": the answer string
// is handed straight to the model, and a bare "Yes" next to "Exceptional Yes"
// reads as a truncation of it - the GM was routinely narrating an ordinary
// success as if the oracle had swung hard. Naming the ordinary result
// explicitly removes the ambiguity without changing what the dice mean.
export type FateAnswer =
  | "Exceptional Yes"
  | "Yes, but"
  | "Normal Yes"
  | "Normal No"
  | "No, but"
  | "Exceptional No";
export type SceneType = "Normal" | "Altered" | "Interrupted";
export type Likelihood =
  | "Impossible"
  | "No Way"
  | "Very Unlikely"
  | "Unlikely"
  | "50/50"
  | "Somewhat Likely"
  | "Likely"
  | "Very Likely"
  | "Near Sure Thing"
  | "A Sure Thing"
  | "Has To Be";

// The Fate Chart, rebuilt from Mythic's own probability ladder rather than
// stored as 99 hand-typed cells.
//
// It used to be a literal table whose cells were authored in Mythic's
// published `[Exceptional Yes, Yes, Exceptional No]` order but read back as
// `[Exceptional No, No, Yes, Exceptional Yes]`, with the likelihood columns
// reversed on top of that. The result was an oracle that answered yes 95% of
// the time to a 50/50 question at the default Chaos Factor (and 50% of the
// time to an "Impossible" one), which is what "the oracle always says yes"
// looked like from the table. Deriving the numbers makes the orientation
// impossible to get wrong again, and `tests/mythicFateChart.test.ts` pins it.
//
// Every target number in Mythic sits on one shared ladder of percentages.
const ODDS_LADDER = [
  1, 3, 5, 10, 15, 25, 35, 50, 65, 75, 85, 90, 95, 97, 99,
];

// Where each likelihood sits on that ladder at Chaos Factor 5 - the neutral
// row, where a 50/50 question is a literal coin flip. The yes half of the
// ladder is finer-grained than the no half because the likelihood labels are
// too (six shades of yes, four of no); the pairs that matter still mirror -
// Impossible/Has To Be at 1%/99%, No Way/A Sure Thing at 5%/95%, Very
// Unlikely/Very Likely at 15%/85%, Unlikely/Somewhat Likely at 35%/65%.
const BASE_LADDER_INDEX: Record<Likelihood, number> = {
  Impossible: 0, // 1%
  "No Way": 2, // 5%
  "Very Unlikely": 4, // 15%
  Unlikely: 6, // 35%
  "50/50": 7, // 50%
  "Somewhat Likely": 8, // 65%
  Likely: 9, // 75%
  "Very Likely": 10, // 85%
  "Near Sure Thing": 11, // 90%
  "A Sure Thing": 12, // 95%
  "Has To Be": 14, // 99%
};

/**
 * The d100 target number a fate question has to roll at or under for a yes.
 *
 * Chaos moves the question one rung along the ladder per point away from 5:
 * a chaotic world bends toward yes, a stable one toward no. That reproduces
 * Mythic's own 50/50 column exactly (10/15/25/35/50/65/75/85/90 for Chaos
 * Factor 1 through 9). Exported for the tests that pin the chart's shape.
 */
export function fateTargetNumber(
  likelihood: Likelihood,
  chaosFactor: number
): number {
  const clampedChaos = Math.max(1, Math.min(9, chaosFactor));
  const index = BASE_LADDER_INDEX[likelihood] + (clampedChaos - 5);
  return ODDS_LADDER[Math.max(0, Math.min(ODDS_LADDER.length - 1, index))];
}

/**
 * Mythic's exceptional-result rule: the bottom fifth of the yes range is an
 * Exceptional Yes, the top fifth of the no range an Exceptional No. Returns
 * the two roll boundaries around the target - a roll at or under
 * `exceptionalYesMax` is an Exceptional Yes, one at or over
 * `exceptionalNoMin` an Exceptional No, and anything in between is an
 * ordinary result on whichever side of `target` it fell.
 *
 * At extreme targets a fifth of the losing range rounds away to nothing
 * (there is no Exceptional Yes at a 1% target, no Exceptional No at 99%),
 * which is the intended behaviour: a near-certain question has no room left
 * to swing.
 */
export function fateThresholds(target: number): {
  exceptionalYesMax: number;
  exceptionalNoMin: number;
  yesButMin: number;
  noButMax: number;
} {
  const yesBand = Math.floor(target / 5);
  const noBand = Math.floor((100 - target) / 5);
  return {
    exceptionalYesMax: yesBand,
    exceptionalNoMin: 100 - noBand + 1,
    // Each side of the target is split into fifths, mirroring the
    // exceptional rule that already carved off the outermost fifth: the
    // fifth *nearest* the target is the qualified result. A yes that only
    // just cleared the number is a yes that cost something; a no that only
    // just missed leaves something salvageable. See the comment on
    // `askFate` for why "but" was missing from the oracle until now.
    //
    // These collapse to nothing at extreme targets, exactly as the
    // exceptional bands do - a 1%-target question has no room for a
    // qualified yes, and `yesButMin > target` is how that's expressed.
    yesButMin: target - yesBand + 1,
    noButMax: target + noBand,
  };
}

/**
 * Roll a d100 (1-100)
 */
function rollD100(): number {
  return Math.floor(Math.random() * 100) + 1;
}

/**
 * Roll a d10 (1-10)
 */
function rollD10(): number {
  return Math.floor(Math.random() * 10) + 1;
}

/**
 * Check if a roll is a random event (doubles on d100)
 */
function isRandomEvent(roll: number): boolean {
  const tens = Math.floor(roll / 10);
  const ones = roll % 10;
  return tens === ones;
}

/**
 * Ask the Fate Question
 * @param likelihood - How likely is a "yes" answer
 * @param chaosFactor - Current chaos level (1-9, default 5)
 * @returns Fate answer and whether a random event occurred
 */
export function askFate(
  likelihood: Likelihood = "50/50",
  chaosFactor: number = 5
): { answer: FateAnswer; randomEvent: boolean; roll: number } {
  // Clamp chaos factor to valid range
  chaosFactor = Math.max(1, Math.min(9, chaosFactor));

  // Validate the likelihood is one the ladder knows
  if (BASE_LADDER_INDEX[likelihood] === undefined) {
    console.error(
      `Invalid AGMT parameters: chaosFactor=${chaosFactor}, likelihood="${likelihood}"`
    );
    // Default to 50/50 if invalid
    likelihood = "50/50";
  }

  const roll = rollD100();
  const target = fateTargetNumber(likelihood, chaosFactor);
  const { exceptionalYesMax, exceptionalNoMin, yesButMin, noButMax } =
    fateThresholds(target);

  // Ordered so every roll from 1 to 100 lands in exactly one branch - the
  // old chain's final `else` swallowed every roll above its top threshold
  // into an Exceptional Yes, so the highest rolls on the die could never
  // come back as a no.
  //
  // The "but" bands subdivide the existing yes and no ranges; they do NOT
  // move the yes/no boundary, so every likelihood's odds of a yes are
  // exactly what they were before (`tests/mythicFateChart.test.ts` pins
  // this). What was missing was the *costed* result: the dice side has had
  // partial success for a long time via formula_roll's stakes and
  // consequences, but the oracle only ever spoke in four absolutes, so
  // every question it answered came back cleanly won or cleanly lost.
  let answer: FateAnswer;
  if (roll <= exceptionalYesMax) {
    answer = "Exceptional Yes";
  } else if (roll <= target) {
    answer = roll >= yesButMin ? "Yes, but" : "Normal Yes";
  } else if (roll >= exceptionalNoMin) {
    answer = "Exceptional No";
  } else {
    answer = roll <= noButMax ? "No, but" : "Normal No";
  }

  const randomEvent = isRandomEvent(roll);

  return { answer, randomEvent, roll };
}

/**
 * Chaos Factor -> sampling temperature nudge (see
 * docs/research-paper-ttrpg-theory-gap-analysis.md §2.4 - a direct
 * implementation of the source paper's "a low Chaos Factor can instruct
 * the system to lower the LLM's temperature... as the Chaos Factor peaks,
 * the system can dynamically increase the LLM's temperature"). Returns a
 * small, bounded delta to ADD on top of whatever base/user-chosen
 * temperature is already in use - this nudges generation volatility with
 * narrative volatility, it does not replace the user's own sampling
 * preference. Chaos Factor 5 (the default, "business as usual") is neutral;
 * 1 (maximally stable) and 9 (maximally chaotic) contribute the full swing.
 *
 * @param chaosFactor - Current chaos level (1-9, default 5)
 */
export function chaosFactorTemperatureDelta(chaosFactor: number = 5): number {
  const clamped = Math.max(1, Math.min(9, chaosFactor));
  return (clamped - 5) * 0.03; // range: -0.12 (chaos 1) .. +0.12 (chaos 9)
}

/**
 * Determine scene setup
 *
 * This is a d10 roll against the chaos factor (1-9), per the AGMT rulebook
 * (also documented independently in docs/mythic_notes.md's "Scene Check"
 * notes) - NOT a d100 roll. A d100 comparison against a 1-9 scale would
 * make Altered/Interrupted results fire on only ~1-9% of scenes even at
 * maximum chaos, instead of the intended roughly-even odds at high chaos.
 *
 * @param chaosFactor - Current chaos level (1-9, default 5)
 * @returns Scene type and roll
 */
export function checkScene(chaosFactor: number = 5): {
  sceneType: SceneType;
  roll: number;
} {
  const roll = rollD10();

  // Scene altered on roll <= chaos factor
  // Scene interrupted on roll <= chaos factor / 2
  if (roll <= Math.floor(chaosFactor / 2)) {
    return { sceneType: "Interrupted", roll };
  } else if (roll <= chaosFactor) {
    return { sceneType: "Altered", roll };
  } else {
    return { sceneType: "Normal", roll };
  }
}

/**
 * Adjust chaos factor based on scene outcome
 * - Increase if scene was chaotic/out of control
 * - Decrease if scene went as planned
 * - Keep same if mixed results
 */
export function adjustChaosFactor(
  currentChaos: number,
  adjustment: -1 | 0 | 1
): number {
  const newChaos = currentChaos + adjustment;
  return Math.max(1, Math.min(9, newChaos));
}

/**
 * Director-layer tension/hope-fear estimate (0-10, default 5).
 *
 * Same clamped-scalar shape as chaos factor, updated at the same
 * increment_scene hook point, but tracking a different thing: how much
 * pressure is currently on the PCs, for the director's move-selection
 * policy to read (see selectDirectorMove below). Escalating signals (an
 * "Interrupted" scene check, active combat, a countdown timer about to
 * hit zero) push it up; a calm "Normal" scene with none of those pushes it
 * back down. An "Altered" scene with no other pressure is neutral.
 */
export interface TensionSignals {
  sceneType: SceneType;
  combatActive?: boolean;
  timerNearZero?: boolean; // Any active CountdownTimer at currentTicks <= 1
}

export function adjustTension(
  currentTension: number,
  signals: TensionSignals
): number {
  const escalating =
    signals.sceneType === "Interrupted" ||
    !!signals.combatActive ||
    !!signals.timerNearZero;
  const calming = signals.sceneType === "Normal" && !escalating;

  const delta = escalating ? 1 : calming ? -1 : 0;
  return Math.max(0, Math.min(10, currentTension + delta));
}

// ============================================
// ORACLE RECENCY
// ============================================
// The oracle used to have no state behind it at all: six places in the
// prompt told the GM to consult it and nothing tracked whether it ever
// did. Everything else the engine actually gets compliance on has
// deterministic pressure behind it (pending random events and director
// moves persist in context until resolved; the M2 gate forces a
// re-prompt). This is the cheap end of that spectrum - no LLM call, no
// gate, just a counter the GM can see climbing.

/**
 * The story's current turn index. Uses scene part count, the same clock
 * selectGMAdviceForTurn seeds its rotation from, so "turns" means the same
 * thing in both places.
 */
export function currentTurnIndex(storyData: StoryData): number {
  return storyData.scene?.parts?.length ?? 0;
}

/**
 * Stamps "the oracle was consulted on this turn" onto agmtState. Called by
 * executeGMTools for any successful fate_question/roll_table - never by the
 * model. No-op when the story has no agmtState (nothing renders the
 * counter in that case either).
 */
export function markOracleConsulted(storyData: StoryData): void {
  if (!storyData.agmtState) return;
  storyData.agmtState.lastOracleTurn = currentTurnIndex(storyData);
}

// Turn gaps at which the counter stops being a neutral readout and starts
// pushing back. Three turns is roughly a scene's worth of beats decided
// without rolling for anything; six is long enough that the GM is near
// certainly settling uncertain facts by what's convenient.
export const ORACLE_NUDGE_THRESHOLD = 3;
export const ORACLE_STRONG_NUDGE_THRESHOLD = 6;

/**
 * The Oracle State line reporting how long it's been since the GM last
 * consulted the oracle, escalating in tone with the gap. Pure - returns the
 * line, the prompt builders decide where it goes.
 */
export function formatOracleRecencyLine(storyData: StoryData): string {
  const turn = currentTurnIndex(storyData);
  const last = storyData.agmtState?.lastOracleTurn;

  if (last === undefined) {
    // A brand-new story hasn't had the chance yet - only start pushing once
    // enough turns have gone by that never having rolled is a real pattern.
    return turn >= ORACLE_NUDGE_THRESHOLD
      ? `- Oracle: 🚨 NEVER consulted in this story (${turn} turns). Every uncertain fact so far is one you decided yourself. Roll \`fate_question\` or \`roll_table\` for the next thing you don't already know.`
      : `- Oracle: not consulted yet`;
  }

  const gap = Math.max(0, turn - last);
  if (gap === 0) return `- Turns since you last consulted the oracle: 0 (this turn)`;
  if (gap < ORACLE_NUDGE_THRESHOLD)
    return `- Turns since you last consulted the oracle: ${gap}`;
  if (gap < ORACLE_STRONG_NUDGE_THRESHOLD)
    return `- Turns since you last consulted the oracle: ${gap} - ⚠️ that's ${gap} turns of world facts, NPC reactions and outcomes you decided on your own. Hand the next uncertain one to \`fate_question\` or \`roll_table\`.`;
  return `- Turns since you last consulted the oracle: ${gap} - 🚨 you are running on your own instincts alone and almost certainly steering toward what's convenient. Consult the oracle this turn unless genuinely nothing is uncertain.`;
}

/**
 * How far through the story the campaign currently is, as a 0-1 fraction.
 * Uses currentChapter/max_chapters - the same progress markers already
 * shown to the player elsewhere in the UI - rather than inventing a new
 * progress signal. Returns 0 for a story with no chapter structure
 * (max_chapters <= 0) rather than dividing by zero.
 */
export function storyProgress(storyData: StoryData): number {
  const maxChapters = storyData.max_chapters || 0;
  if (maxChapters <= 0) return 0;
  return Math.max(
    0,
    Math.min(1, (storyData.currentChapter || 0) / maxChapters)
  );
}

/**
 * Freytag-shaped target tension curve (0-10) for a given story progress
 * (0-1): a calm opening rises through the middle toward a climax window,
 * then releases into a falling-action/resolution close. This is a *target*
 * the director layer can compare the live, reactive `tension` scalar
 * against - it never overrides `adjustTension`'s own per-scene nudges, it
 * only tells `selectDirectorMove` when the story is falling noticeably
 * behind its own dramatic arc (e.g. still calm well past the midpoint) so
 * it can proactively raise stakes instead of only reacting after the fact.
 */
export function targetTensionForProgress(progress: number): number {
  const p = Math.max(0, Math.min(1, progress));
  if (p < 0.6) {
    // Rising action: climbs from a calm opening toward the climax window.
    return 2 + (p / 0.6) * 6; // 2 -> 8
  }
  if (p < 0.8) {
    // Climax window: sustained high tension.
    return 8 + ((p - 0.6) / 0.2) * 1; // 8 -> 9
  }
  // Falling action / resolution: tension releases toward a calmer close.
  return 9 - ((p - 0.8) / 0.2) * 6; // 9 -> 3
}

// How far below the macro-arc's target tension the live tension scalar must
// fall before the director proactively raises stakes to catch the story
// back up to its own arc, rather than waiting for a reactive escalation.
const ARC_LAG_THRESHOLD = 3;

// Deliberately narrow, keyword-only classification of what a PLAYER typed -
// never the GM's own narration (that would risk grading prose, the
// unreliable pattern this codebase's audit history rules out elsewhere).
// Same class of lightweight regex heuristic already used in
// embeddings.ts's calculateMemoryImportance. First match wins; ambiguous or
// keyword-free input classifies as null (no signal), not guessed.
const ACTION_KEYWORDS =
  /\b(attack|fight|strike|shoot|charge|kill|stab|swing|punch|slash|dodge|block|chase)\b/i;
const SOCIAL_KEYWORDS =
  /\b(ask|tell|talk|say|persuade|negotiate|convince|greet|apologize|lie|flirt|threaten|charm|explain)\b/i;
const TACTICAL_KEYWORDS =
  /\b(search|investigate|examine|inspect|sneak|hide|check|study|analyze|plan|scout|pick|unlock|look)\b/i;

/**
 * Classifies a player's own freeform input into a lightweight PaSSAGE-
 * inspired style bucket (Robin Laws' player-type taxonomy, narrowed to
 * three deterministically-detectable buckets). Returns null when nothing
 * matches - "no signal" is preferred over guessing.
 */
export function classifyPlayerStyle(input: string): PlayerStyleType | null {
  if (ACTION_KEYWORDS.test(input)) return "action";
  if (SOCIAL_KEYWORDS.test(input)) return "social";
  if (TACTICAL_KEYWORDS.test(input)) return "tactical";
  return null;
}

// Deterministic, name-based classification of what a turn's GM tool
// activity actually *did* - a second, independent signal alongside
// classifyPlayerStyle's freeform-text keyword read of what the player
// *typed*. Neither replaces the other; page.tsx blends both into the same
// playerStyleCounts accumulator. Tool names not listed here contribute no
// signal (formula_roll, add_memory, etc. are too generic to imply a style
// on their own).
const ACTION_TOOL_NAMES = new Set([
  "start_combat",
  "add_combatant",
  "remove_combatant",
  "update_combatant_stat",
  "toggle_combatant_condition",
  "advance_turn",
  "end_combat",
  "opposed_formula",
]);
const SOCIAL_TOOL_NAMES = new Set(["npc_reaction", "update_npc"]);
const TACTICAL_TOOL_NAMES = new Set([
  "start_challenge",
  "update_challenge",
  "resolve_challenge",
  "cancel_challenge",
  "record_challenge_result",
  "search_memory",
  "read_notes",
  "roll_table",
  "manage_timer",
  "calculate",
]);

/**
 * Classifies a turn's GM tool-call activity into the same lightweight style
 * buckets as classifyPlayerStyle, by counting which category each called
 * tool falls into. Returns the bucket with the most matches, or null when
 * there's no signal (no matching tools called) or the top two buckets are
 * tied (an ambiguous turn shouldn't guess a style any more than ambiguous
 * freeform text should).
 */
export function classifyToolActivityStyle(
  toolNames: string[]
): PlayerStyleType | null {
  let action = 0;
  let social = 0;
  let tactical = 0;
  for (const name of toolNames) {
    if (ACTION_TOOL_NAMES.has(name)) action++;
    else if (SOCIAL_TOOL_NAMES.has(name)) social++;
    else if (TACTICAL_TOOL_NAMES.has(name)) tactical++;
  }

  const counts: [PlayerStyleType, number][] = [
    ["action", action],
    ["social", social],
    ["tactical", tactical],
  ];
  counts.sort((a, b) => b[1] - a[1]);

  if (counts[0][1] === 0 || counts[0][1] === counts[1][1]) return null;
  return counts[0][0];
}

/** The style with the highest observed count, or null if there's no signal yet. */
export function dominantPlayerStyle(
  counts: Record<PlayerStyleType, number> | undefined
): PlayerStyleType | null {
  if (!counts) return null;
  const withSignal = (
    Object.entries(counts) as [PlayerStyleType, number][]
  ).filter(([, n]) => n > 0);
  if (withSignal.length === 0) return null;
  withSignal.sort((a, b) => b[1] - a[1]);
  return withSignal[0][0];
}

// Minimum consecutive turns a couch player must have gone unheard before
// selectDirectorMove will spotlight them - low enough to matter in a short
// session, high enough not to nag every turn in a fast-moving scene.
const SPOTLIGHT_NEGLECT_THRESHOLD = 3;

// How close two players' neglect counts must be to be considered "tied" for
// spotlight purposes - close enough that style preference is a reasonable
// tiebreaker, not so wide that it overrides basic fairness of screen time.
const SPOTLIGHT_TIE_WINDOW = 1;

// Given the current scene's pressure, which player style best fits being
// put in the spotlight right now - a high-tension moment suits an
// action-styled player more than a calm one, a chaotic scene check suits
// investigation, and a routine/calm moment suits social/dialogue framing.
function preferredStyleForScene(
  tension: number,
  sceneType: SceneType
): PlayerStyleType {
  if (tension >= 7) return "action";
  if (sceneType === "Interrupted" || sceneType === "Altered") return "tactical";
  return "social";
}

// A (tag, whose tag it is) pair the spotlight_tag move can pick from -
// flattened from wherever the player(s) actually picked tags at story
// start: per-CouchPlayer for couch co-op, or the solo StoryData fields when
// there's no couch roster at all (see StoryData.playerPersonalityTags/
// playerWishTags and CouchPlayer.personalityTags/wishTags in structs.ts).
interface TagCandidate {
  tag: string;
  playerName: string;
}

// Gathers every curated personality/wish tag any player picked in the
// GuidedStoryStart wizard, tagged with whose it is. Empty for older saves
// or anyone who skipped/typed past the wizard - spotlight_tag is simply
// unavailable then, the same "no data, no move" posture activate_downside's
// revert already established for this codebase (see
// docs/architecture-frontier.md's Frontier 3 note on that revert).
function availableTagCandidates(storyData: StoryData): TagCandidate[] {
  const couchPlayers = storyData.multiplayer?.couchPlayers || [];
  if (couchPlayers.length > 0) {
    return couchPlayers.flatMap((p) => [
      ...(p.personalityTags || []).map((tag) => ({ tag, playerName: p.name })),
      ...(p.wishTags || []).map((tag) => ({ tag, playerName: p.name })),
    ]);
  }

  const playerName = storyData.player_name || "The player";
  return [
    ...(storyData.playerPersonalityTags || []).map((tag) => ({
      tag,
      playerName,
    })),
    ...(storyData.playerWishTags || []).map((tag) => ({ tag, playerName })),
  ];
}

// Given a list of active threads, picks whichever has gone longest without
// director-assistant-judged spotlight (storyData.directorAssistant.
// threadSpotlight - see directorAssistant.ts). Falls back to array order
// (the previous activeThreads[0] behavior) when no ledger data exists yet
// for any of them - e.g. a fresh story, or one where the Director Assistant
// hasn't run yet (it only runs on scene increments, and only once threads
// exist to judge). Still deterministic: the engine picks the target, the
// LLM only supplied the neglect signal it's picking from.
function mostNeglectedThread(
  storyData: StoryData,
  threads: StoryThread[]
): StoryThread | undefined {
  if (threads.length === 0) return undefined;
  const ledger = storyData.directorAssistant?.threadSpotlight || {};
  let chosen = threads[0];
  let chosenNeglect = ledger[chosen.id] ?? 0;
  for (const thread of threads.slice(1)) {
    const neglect = ledger[thread.id] ?? 0;
    if (neglect > chosenNeglect) {
      chosen = thread;
      chosenNeglect = neglect;
    }
  }
  return chosen;
}

// Same pattern as mostNeglectedThread, for NPCs (storyData.directorAssistant.
// npcSpotlight, keyed by NPC.name).
function mostNeglectedNpc(storyData: StoryData, npcs: NPC[]): NPC | undefined {
  if (npcs.length === 0) return undefined;
  const ledger = storyData.directorAssistant?.npcSpotlight || {};
  let chosen = npcs[0];
  let chosenNeglect = ledger[chosen.name] ?? 0;
  for (const npc of npcs.slice(1)) {
    const neglect = ledger[npc.name] ?? 0;
    if (neglect > chosenNeglect) {
      chosen = npc;
      chosenNeglect = neglect;
    }
  }
  return chosen;
}

/**
 * Deterministic GM-move selection policy (PbtA-style bounded move menu).
 *
 * This is the director layer's equivalent of the oracle: the engine decides
 * WHICH move fires and WHEN, from live state - never the model's own
 * judgment (the same anti-pattern H7 already closed for reasoning-tier
 * self-escalation applies here: a model that could pick its own move would
 * reliably pick the gentlest one). The model only renders the chosen move
 * as prose ("make your move, but never speak its name") after calling
 * acknowledge_director_move - see ai_staged.ts/toolExecutor.ts.
 *
 * Priority order: a timer about to trigger outranks a chaotic scene check,
 * which outranks high sustained tension, which outranks a neglected couch
 * player (spotlight_couch_player - only relevant once there's more than one
 * couchPlayer; a no-op for the single-player majority case), which outranks
 * a queued lore reveal (reveal_unwelcome_truth), which outranks bringing one
 * of a player's story-start tags into focus (spotlight_tag - a no-op if
 * nobody picked any tags), which outranks the generic open-thread fallback
 * (offer_opportunity). Returns null when nothing warrants a move, or when
 * one is already pending and unacknowledged (a simple anti-pileup throttle -
 * address what's already on the table before adding more).
 */
export function selectDirectorMove(
  storyData: StoryData,
  sceneType: SceneType
): PendingDirectorMove | null {
  if ((storyData.pendingDirectorMoves?.length || 0) > 0) {
    return null;
  }

  const tension = storyData.agmtState?.tension ?? 5;
  const activeThreads = (storyData.threads || []).filter(
    (t) => t.status === "active"
  );
  const activeTimers = (storyData.timers || []).filter(
    (t) => t.status === "active"
  );

  const nearZeroTimer = activeTimers.find((t) => t.currentTicks <= 1);
  if (nearZeroTimer) {
    const linkedThread = activeThreads.find(
      (t) => t.linkedTimerId === nearZeroTimer.id
    );
    return {
      id: crypto.randomUUID(),
      move: "tick_a_clock",
      targetTimerId: nearZeroTimer.id,
      targetThreadId: linkedThread?.id,
      context: `Timer "${nearZeroTimer.name}" is about to trigger`,
      createdAt: Date.now(),
    };
  }

  if (sceneType === "Interrupted" || sceneType === "Altered") {
    const thread = mostNeglectedThread(storyData, activeThreads);
    return {
      id: crypto.randomUUID(),
      move: "announce_future_badness",
      targetThreadId: thread?.id,
      context: `Scene check result: ${sceneType}`,
      complicationSeed: rollComplication().result,
      createdAt: Date.now(),
    };
  }

  if (tension >= 8) {
    // Hardness dimensions extended to the Director layer (see
    // docs/research-paper-ttrpg-theory-gap-analysis.md §2.2 follow-up):
    // at the hard tension ceiling, force the consequence into a genuine
    // dilemma, and land it on an already-tracked allied NPC when one
    // exists - the same "engine decides, deterministically, from
    // already-tracked state" pattern targetThreadId/targetTimerId below
    // already use, not invented judgment. Deliberately only applied at
    // this single, most-severe trigger - not a general dial on every move.
    const alliedNpcs = (storyData.npcs || []).filter(
      (n) => n.attitude === "allied"
    );
    // Prefer whichever allied NPC the spotlight ledger says has gone longest
    // without focus (falls back to the first tracked one with no ledger data
    // yet) - named directly in context so the neglect signal actually
    // changes which NPC the GM is nudged toward, not just whether the
    // hardness dimension fires at all.
    const alliedNpc = mostNeglectedNpc(storyData, alliedNpcs);
    return {
      id: crypto.randomUUID(),
      move: "put_someone_in_a_spot",
      context: alliedNpc
        ? `Tension running high (${tension}/10) - ${alliedNpc.name} hasn't had recent focus`
        : `Tension running high (${tension}/10)`,
      hardnessForcesChoice: true,
      hardnessTarget: alliedNpc ? "someone_they_love" : undefined,
      complicationSeed: rollComplication().result,
      createdAt: Date.now(),
    };
  }

  // Macro-arc awareness: even when nothing in the current scene is escalating,
  // check whether the live tension scalar has fallen noticeably behind where
  // the story's own dramatic arc (targetTensionForProgress) says it should be
  // by this point - e.g. still calm well past the midpoint of the campaign.
  // This is what lets the director proactively raise stakes toward a climax
  // instead of only ever reacting to whatever just happened in-scene.
  const targetTension = targetTensionForProgress(storyProgress(storyData));
  if (tension < targetTension - ARC_LAG_THRESHOLD) {
    return {
      id: crypto.randomUUID(),
      move: "put_someone_in_a_spot",
      context: `Story pacing is lagging its arc (tension ${tension}/10 vs. an expected ~${Math.round(
        targetTension
      )}/10 at this point in the story)`,
      complicationSeed: rollComplication().result,
      createdAt: Date.now(),
    };
  }

  // Couch co-op spotlight tracking: bias toward whichever player has gone
  // the longest without speaking (ScenePart.speakerIds / couchPlayerFocus,
  // updated client-side in page.tsx's handleCustomInput). No-op for
  // single-player stories - the overwhelming majority. Fairness of screen
  // time always comes first - player-style modeling (playerStyleCounts)
  // only breaks a close tie between similarly-neglected players, it never
  // overrides who's actually most overdue.
  const couchPlayers = storyData.multiplayer?.couchPlayers || [];
  if (couchPlayers.length > 1) {
    const focus = storyData.multiplayer?.couchPlayerFocus || {};
    const styleCounts = storyData.multiplayer?.playerStyleCounts || {};

    let maxTurnsSinceSpoken = -1;
    for (const player of couchPlayers) {
      maxTurnsSinceSpoken = Math.max(maxTurnsSinceSpoken, focus[player.id] ?? 0);
    }

    if (maxTurnsSinceSpoken >= SPOTLIGHT_NEGLECT_THRESHOLD) {
      const candidates = couchPlayers.filter(
        (p) => maxTurnsSinceSpoken - (focus[p.id] ?? 0) <= SPOTLIGHT_TIE_WINDOW
      );

      let chosen: CouchPlayer = candidates[0];
      if (candidates.length > 1) {
        const preferredStyle = preferredStyleForScene(tension, sceneType);
        const styleMatch = candidates.find(
          (p) => dominantPlayerStyle(styleCounts[p.id]) === preferredStyle
        );
        if (styleMatch) chosen = styleMatch;
      }

      return {
        id: crypto.randomUUID(),
        move: "spotlight_couch_player",
        targetCouchPlayerId: chosen.id,
        context: `${chosen.name} hasn't had the spotlight in ${
          focus[chosen.id] ?? 0
        } turns`,
        createdAt: Date.now(),
      };
    }
  }

  // Another soft, non-escalating default for the calm case: PbtA's "reveal
  // an unwelcome truth" maps directly onto this app's own Two-Pass
  // Visibility system (StoryLore.visibility === "to_be_revealed" - a
  // secret already queued to surface eventually, see
  // docs/research-paper-ttrpg-theory-gap-analysis.md §2.3). That system's
  // own design leaves *when* to reveal one entirely to the model's
  // narrative judgment; this move gives it a deterministic nudge instead
  // of relying on the model to remember a backlog of pending secrets on
  // its own. The model still does the actual reveal (prose plus flipping
  // the entry's visibility via edit_lore/edit_note, unchanged) - this only
  // says "now's a good time," the same "engine decides when, model decides
  // how" split every other move already uses. Checked before
  // offer_opportunity below: clearing a pending secret takes priority over
  // purely optional flavor.
  const revealableLore = (storyData.lore || []).find(
    (l) => l.visibility === "to_be_revealed" && l.enabled !== false
  );
  if (revealableLore) {
    return {
      id: crypto.randomUUID(),
      move: "reveal_unwelcome_truth",
      targetLoreTitle: revealableLore.title,
      context: `"${revealableLore.title}" is queued to be revealed`,
      createdAt: Date.now(),
    };
  }

  // A third soft, non-escalating calm-scene default: bring one of the
  // curated personality/wish tags a player picked at story start into
  // focus, rather than only ever reacting to tracked plot state. Checked
  // before offer_opportunity (below) since it needs no active thread to
  // fire from - just any player having picked at least one tag - so it's a
  // strictly better calm-scene default than offer_opportunity whenever
  // tags are available. A no-op (falls through to offer_opportunity) for
  // older saves or anyone who skipped the wizard's tag step. The engine
  // only picks WHICH tag/player and samples 3 of that tag's 10 curated
  // examples (pickTagFocusExamples, tagFocusExamples.ts) as inspiration -
  // the model still chooses how to actually play it out, same split as
  // every other move.
  const tagCandidates = availableTagCandidates(storyData);
  if (tagCandidates.length > 0) {
    const choice =
      tagCandidates[Math.floor(Math.random() * tagCandidates.length)];
    const examples = pickTagFocusExamples(choice.tag, 3);
    if (examples.length > 0) {
      return {
        id: crypto.randomUUID(),
        move: "spotlight_tag",
        targetPlayerName: choice.playerName,
        targetTag: choice.tag,
        tagFocusExamples: examples,
        context: `Bringing ${choice.playerName}'s "${choice.tag}" tag into focus`,
        createdAt: Date.now(),
      };
    }
  }

  // Soft, non-escalating move for the common "nothing's wrong" case: PbtA's
  // own move list isn't only about danger - "offer an opportunity, with or
  // without a cost" is the classic default for an otherwise uneventful
  // scene. Everything above this point already covers the escalating
  // signals (timer, chaotic scene check, tension ceiling, arc lag, a
  // neglected couch player, a pending secret reveal); reaching here means
  // the scene resolved normally and pacing is on track, which used to mean
  // no move fired at all. Gated on there being an active thread to hang
  // the opportunity on (the same "engine decides from already-tracked
  // state" pattern the other moves use) - with nothing open to offer an
  // opportunity about, this stays a no-op rather than inventing one from
  // nothing.
  if (activeThreads.length > 0) {
    return {
      id: crypto.randomUUID(),
      move: "offer_opportunity",
      targetThreadId: mostNeglectedThread(storyData, activeThreads)!.id,
      context: `Scene resolved normally, pacing on track (tension ${tension}/10)`,
      createdAt: Date.now(),
    };
  }

  return null;
}

