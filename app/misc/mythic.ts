/**
 * Generate event meaning (Action + Subject)
 */
export function generateEventMeaning(): {
  action: string;
  subject: string;
  actionRoll: number;
  subjectRoll: number;
} {
  const actionRoll = rollD100();
  const subjectRoll = rollD100();

  const actionIndex = Math.min(actionRoll - 1, EVENT_ACTIONS.length - 1);
  const subjectIndex = Math.min(subjectRoll - 1, EVENT_SUBJECTS.length - 1);

  return {
    action: EVENT_ACTIONS[actionIndex],
    subject: EVENT_SUBJECTS[subjectIndex],
    actionRoll,
    subjectRoll,
  };
}

/**
 * Complete Advanced RPG Tools state and utilities
 */
export interface AGMTState {
  chaosFactor: number;
  threads: string[];
  npcs: string[];
  sceneCount: number;
}

/**
 * Create a new Advanced RPG Tools state
 */
export function createAGMTState(): AGMTState {
  return {
    chaosFactor: 5,
    threads: [],
    npcs: [],
    sceneCount: 0,
  };
}

/**
 * Complete scene setup and random event check
 *
 * An Interrupted scene check IS the random-event trigger (the expected
 * scene doesn't happen - a random event replaces it) - it isn't a
 * separate doubles condition on the scene-check roll. (Doubles-based
 * random event detection is a distinct mechanic that belongs to d100
 * rolls, e.g. askFate's own roll via isRandomEvent - it doesn't apply to
 * this d10 scene-check roll.)
 */
export function setupScene(state: AGMTState): {
  sceneType: SceneType;
  sceneRoll: number;
  randomEvent: boolean;
  eventFocus?: string;
  eventMeaning?: { action: string; subject: string };
} {
  const { sceneType, roll: sceneRoll } = checkScene(state.chaosFactor);
  const randomEvent = sceneType === "Interrupted";

  let eventFocus: string | undefined;
  let eventMeaning: { action: string; subject: string } | undefined;

  if (randomEvent) {
    const focusResult = generateEventFocus();
    eventFocus = focusResult.focus;

    const meaningResult = generateEventMeaning();
    eventMeaning = {
      action: meaningResult.action,
      subject: meaningResult.subject,
    };
  }

  return {
    sceneType,
    sceneRoll,
    randomEvent,
    eventFocus,
    eventMeaning,
  };
}
