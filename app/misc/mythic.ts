/**
 * Roll a d100 (1-100)
 */
function rollD100(): number {
  return Math.floor(Math.random() * 100) + 1;
}

/**
 * Roll a d10 (1-10)
 */
function rollD10(): number {
  return Math.floor(Math.random() * 10) + 1;
}

/**
 * Check if a roll is a random event (doubles on d100)
 */
function isRandomEvent(roll: number): boolean {
  const tens = Math.floor(roll / 10);
  const ones = roll % 10;
  return tens === ones;
}

/**
 * Ask the Fate Question
 * @param likelihood - How likely is a "yes" answer
 * @param chaosFactor - Current chaos level (1-9, default 5)
 * @returns Fate answer and whether a random event occurred
 */
export function askFate(
  likelihood: Likelihood = "50/50",
  chaosFactor: number = 5
): { answer: FateAnswer; randomEvent: boolean; roll: number } {
  // Clamp chaos factor to valid range
  chaosFactor = Math.max(1, Math.min(9, chaosFactor));

  // Validate likelihood exists in chart
  if (!FATE_CHART[chaosFactor] || !FATE_CHART[chaosFactor][likelihood]) {
    console.error(
      `Invalid AGMT parameters: chaosFactor=${chaosFactor}, likelihood="${likelihood}"`
    );
    // Default to 50/50 if invalid
    likelihood = "50/50";
  }

  const roll = rollD100();
  const thresholds = FATE_CHART[chaosFactor][likelihood];
  const [exceptionalNo, no, yes, exceptionalYes] = thresholds;

  let answer: FateAnswer;
  if (roll <= exceptionalNo) {
    answer = "Exceptional No";
  } else if (roll <= no) {
    answer = "No";
  } else if (roll <= yes) {
    answer = "Yes";
  } else if (roll <= exceptionalYes) {
    answer = "Exceptional Yes";
  } else {
    // Above exceptional yes threshold
    answer = "Exceptional Yes";
  }

  const randomEvent = isRandomEvent(roll);

  return { answer, randomEvent, roll };
}

/**
 * Determine scene setup
 *
 * This is a d10 roll against the chaos factor (1-9), per the AGMT rulebook
 * (also documented independently in docs/mythic_notes.md's "Scene Check"
 * notes) - NOT a d100 roll. A d100 comparison against a 1-9 scale would
 * make Altered/Interrupted results fire on only ~1-9% of scenes even at
 * maximum chaos, instead of the intended roughly-even odds at high chaos.
 *
 * @param chaosFactor - Current chaos level (1-9, default 5)
 * @returns Scene type and roll
 */
export function checkScene(chaosFactor: number = 5): {
  sceneType: SceneType;
  roll: number;
} {
  const roll = rollD10();

  // Scene altered on roll <= chaos factor
  // Scene interrupted on roll <= chaos factor / 2
  if (roll <= Math.floor(chaosFactor / 2)) {
    return { sceneType: "Interrupted", roll };
  } else if (roll <= chaosFactor) {
    return { sceneType: "Altered", roll };
  } else {
    return { sceneType: "Normal", roll };
  }
}

/**
 * Adjust chaos factor based on scene outcome
 * - Increase if scene was chaotic/out of control
 * - Decrease if scene went as planned
 * - Keep same if mixed results
 */
export function adjustChaosFactor(
  currentChaos: number,
  adjustment: -1 | 0 | 1
): number {
  const newChaos = currentChaos + adjustment;
  return Math.max(1, Math.min(9, newChaos));
}

